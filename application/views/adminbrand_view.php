      function clearall(){
         $('#modalcaption').text("Add Brand");
        $('#image_file').val('');
         $('#brandid').val('');
        $('#brandname').val('');
         $('#brandimage').val('');
          $("#brandimage").prop('required',true);
         $('#imagefill').html('');
         $('#imagehid').val('');
          getbrand();
        // $('#userfullname').val('');
        // $('#userfullname').val('');    
      }
      

      $("#idFormBrand").submit(function(e) {
         e.preventDefault(); 
         var form = $(this);
         $.ajax({
                method: "POST",
                url: "<?php echo base_url('index.php/Adminbrandmanage/insertbrand');?>/",
               // data: form.serialize(), // serializes the form's elements.
                data:new FormData(this),  
                     contentType: false,  
                     cache: false,  
                     processData:false, 
               success: function(data){
               if(data == "success"){
                  notifyresult('Data Saved','success');
                  $('#trackermodal').modal('hide');
                   getbrand();
               }else{
                  notifyresult('Error','danger');
                  $('#trackermodal').modal('hide');
               }

              // show response from the php script.            
              }
             });
      });
      
      function editbrand(id){
        $('#modalcaption').text("Edit Brand");
        $('#brandimage').val('');
        $.ajax({
              method: "POST",
              url: "<?php echo base_url('index.php/Adminbrandmanage/editbrand');?>/",
              data: {id:id}, // serializes the form's elements.
             success: function(data){
              var res = JSON.parse(data);
              // console.log(data);
              // $('#image_file').val('');
               $("#brandimage").prop('required',false);
              $('#brandid').val(res.brand_id);
              $('#brandname').val(res.brand_name);
             $('#imagefill').html('<img  style="width:250px;height:200px;"src="<?php echo base_url();?>/imageupload/'+res.brand_image+'">')
              
              $('#imagehid').val(res.brand_image);
            }
        });
      }
      
      function deletebrand(id,img){
        var result = confirm("Are you want to delete?");
          if (result) {
              $.ajax({
              method: "POST",
              url: "<?php echo base_url('index.php/Adminbrandmanage/deletebrand');?>/",
              data: {id:id,imagename:img}, // serializes the form's elements.
             success: function(data){
              if(data == "success"){
                  notifyresult('Data Deleted','success');
                   getbrand();
               }else{
                  notifyresult('Error','danger');
               }
               

            }
        });
          }
        
      }
