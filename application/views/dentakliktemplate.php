    }

    function checkmailsendcode()
    {
        var mailid = $('#umail').val();
        
        $.ajax({
                 async: false,
                method: "POST",
                url: "<?php echo base_url('index.php/Register_user/checkmailsendcod');?>/",
                data: {mailid:mailid}, // serializes the form's elements.
               success: function(data){
                
                alert(data);

                if($.trim(data)=='success')
                   {
                      $('#mailerrorspan').css('color','green');
                      $('#mailerrorspan').text('Code send.please check your mail id');
                      $('#uregsub').attr('disabled',false); 
